// Converts an ISO alpha-2 code (e.g. "NO") into its flag emoji using the
// two matching Unicode regional indicator symbols.
export function flagEmoji(iso2) {
  return iso2
    .toUpperCase()
    .replace(/./g, (c) => String.fromCodePoint(127397 + c.charCodeAt(0)));
}
